"""Formula Legends -- the pit crew made in Blender (tools/blender/pit_crew.py) as game models.

    python3 tools/gen_crew.py [preview_dir]

Reads tools/blender/pit_crew.json (one body, 16 poses: idle, wheel gun, push, celebrate x 4) and
writes crew_<motion>_<pose>.emm and pit_crew.emm to DATA/models (PSP) and HD/models (Vita).
Every pose has the same triangles in the same order, so the game can blend two of them
(Renderer::drawPerson). The suit is flat colours, so the whole crew shares one 64 px texture,
stored once in crew_idle_0.emm.
"""
import json, os, struct, sys
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
from build_models import swizzle                 # noqa: E402

SRC = os.path.join(HERE, 'blender', 'pit_crew.json')
ANIMS = ('idle', 'wheelgun', 'push', 'celebrate')
TEX = 64
KEY = np.array([0.45, 0.35, 0.82]); KEY /= np.linalg.norm(KEY)


# the team's colours go into fixed palette entries (the game swaps them per team, Renderer::drawPerson):
# 1 suit (main), 2 accent flashes (second), 3 helmet (main), 4 helmet stripe (second)
ROLES = ('suit', 'accent', 'helmet', 'stripe')


def team_header():
    """src/team_colours.h: each F1 team's second colour (gen_f1.STYLES), for the crew and helmets"""
    import ast, re
    src = open(os.path.join(HERE, 'gen_f1.py')).read()
    a = src.index('STYLES = {'); b = src.index('\n}\n', a) + 2
    styles = ast.literal_eval(re.sub(r'#.*', '', src[a + len('STYLES = '):b]))
    def abgr(c):
        r, g, b_ = (int(round(max(0, min(1, x)) * 255)) for x in c)
        return 0xFF000000 | (b_ << 16) | (g << 8) | r
    rows = ''.join(f'    {{"{k}", 0x{abgr(v[0]):08X}u}},\n' for k, v in sorted(styles.items()))
    open(os.path.join(ROOT, 'src', 'team_colours.h'), 'w').write(
        '// generated by tools/gen_crew.py from the livery styles in tools/gen_f1.py: each team\'s second\n'
        '// colour (ABGR), for its pit crew\'s suits and its helmets. Teams not listed use white.\n'
        '#pragma once\n#include <cstdint>\n'
        'struct TeamSecond { const char* id; uint32_t abgr; };\n'
        f'static const TeamSecond TEAM_SECOND[] = {{\n{rows}}};\n')
    return len(styles)


def main(prev=None):
    d = json.load(open(SRC))
    # the texture: one 8 x 8 cell of flat colour per material, the whole cell filled (so the small
    # mip levels keep the colour); the pixel value is the palette entry
    order = [m for m in ROLES if m in d['materials']] + [m for m in d['materials'] if m not in ROLES]
    assert order[:4] == list(ROLES), order
    pal = [0xFF808080] * 256
    pix = np.zeros((TEX, TEX), np.uint8)
    cell = {}
    for k, m in enumerate(order):
        r, g, b = (int(round(c * 255)) for c in d['palette'][m])
        pal[k + 1] = 0xFF000000 | (b << 16) | (g << 8) | r
        cx, cy = (k % 8) * 8, (k // 8) * 8
        pix[cy:cy + 8, cx:cx + 8] = k + 1
        cell[m] = ((cx + 4) / TEX, (cy + 4) / TEX)
    tris = np.array(d['m'])
    uv = np.zeros((len(tris) * 3, 2))
    for i, mi in enumerate(tris):
        uv[i * 3:i * 3 + 3] = cell[d['materials'][mi]]
    uv16 = np.clip(np.round(uv * 32767), 0, 65535).astype(np.uint16)
    sw = swizzle(pix.reshape(-1), TEX, TEX)
    print('teams with a second colour:', team_header())

    poses = {(an, f): (np.array(fr['p'], np.float32).reshape(-1, 3), np.array(fr['n'], np.float32).reshape(-1, 3))
             for an in ANIMS for f, fr in enumerate(d['anims'][an])}
    # one shared scale for every pose; each motion stood on the ground by its lowest point
    grounded = {}
    for an in ANIMS:
        g = min(poses[(an, f)][0][:, 2].min() for f in range(4))
        for f in range(4):
            p = poses[(an, f)][0].copy(); p[:, 2] -= g
            grounded[(an, f)] = p
    allp = np.concatenate(list(grounded.values()))
    half = np.abs(allp).max(0) * 1.02
    hz = allp[:, 2].max() * 1.02 / 2
    scale = [float(half[0]), float(half[1]), float(hz)]

    def write(path, p, n, tex):
        p = p - np.array([0, 0, hz])                        # stored centred; the header lifts it back
        q = np.clip(np.round(p / np.array(scale) * 32767), -32767, 32767).astype(np.int16)
        n = n / np.maximum(np.linalg.norm(n, axis=1, keepdims=True), 1e-6)
        light = 0.50 + 0.30 * (n[:, 2] * 0.5 + 0.5) + 0.30 * np.clip(n @ KEY, 0, 1)
        g = np.clip(np.round(light * 255), 0, 255).astype(np.uint32)
        rec = np.zeros(len(p), dtype=[('u', '<u2'), ('v', '<u2'), ('c', '<u4'), ('x', '<i2'), ('y', '<i2'), ('z', '<i2'), ('pad', '<i2')])
        rec['u'] = uv16[:, 0]; rec['v'] = uv16[:, 1]; rec['c'] = 0xFF000000 | (g << 16) | (g << 8) | g
        rec['x'] = q[:, 0]; rec['y'] = q[:, 1]; rec['z'] = q[:, 2]
        with open(path, 'wb') as fo:
            fo.write(b'EMM1'); fo.write(struct.pack('<I', 1))
            fo.write(struct.pack('<3f', *scale)); fo.write(struct.pack('<3f', 0.0, 0.0, float(hz)))
            fo.write(struct.pack('<IIII', len(p), TEX if tex else 0, 0, 0))
            if tex:
                fo.write(struct.pack('<256I', *pal)); fo.write(sw.tobytes())
            fo.write(rec.tobytes())

    total = 0
    for folder in ('DATA/models', 'HD/models'):
        out = os.path.join(ROOT, folder)
        for (an, f), p in grounded.items():
            fn = os.path.join(out, f'crew_{an}_{f}.emm')
            write(fn, p, poses[(an, f)][1], (an, f) == ('idle', 0))     # only the first pose carries the texture
            total += os.path.getsize(fn)
        fn = os.path.join(out, 'pit_crew.emm')                         # the still man (no poses loaded)
        write(fn, grounded[('idle', 0)], poses[('idle', 0)][1], True)
        total += os.path.getsize(fn)
    print(f'crew: {len(tris)} triangles, 16 poses, scale {np.round(scale, 3).tolist()}, '
          f'{total / 2 / 1024:.0f} KB a set (DATA and HD)')


if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else None)
